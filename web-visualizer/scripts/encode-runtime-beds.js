/**
 * Encode selectable WAV masters to mono WebM/Opus and AAC/M4A for playback.
 * WAV files stay the archive. The diagnostics menu keeps listing them.
 * Playback files are written to sample-runtime/ at the repo root.
 * The runtime map stays in public/. The catalog walk never sees the AAC files.
 */
const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SAMPLES_DIR = path.join(ROOT, "..", "sample-master");
const BEDS_DIR = path.join(ROOT, "..", "sample-master", "beds");
const RUNTIME_DIR = path.join(ROOT, "..", "sample-runtime");
const MAP_FILE = path.join(ROOT, "public", "runtime-beds.js");

const SOURCE_EXTS = new Set([".wav", ".aif", ".aiff", ".mp3", ".ogg", ".flac"]);
const NATURE_FILES = ["Beach-rx.wav", "Forest-rx.wav", "River-rx.wav"];
const LOOP_CROSSFADE = 0.012;

function urlFor(parts) {
  return `/${parts.map((part) => encodeURIComponent(part)).join("/")}`;
}

function walkSamples(absDir, relParts, out) {
  if (!fs.existsSync(absDir)) return;
  for (const entry of fs.readdirSync(absDir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const abs = path.join(absDir, entry.name);
    const parts = relParts.concat(entry.name);
    if (entry.isDirectory()) {
      if (relParts.length === 0 && entry.name === "beds") continue;
      walkSamples(abs, parts, out);
      continue;
    }
    if (!entry.isFile()) continue;
    if (!SOURCE_EXTS.has(path.extname(entry.name).toLowerCase())) continue;
    out.push({
      abs,
      masterUrl: urlFor(["samples", ...parts]),
      runtimeParts: ["sample-runtime", "samples", ...parts],
    });
  }
}

function collectSources() {
  const sources = [];
  walkSamples(SAMPLES_DIR, [], sources);
  for (const name of NATURE_FILES) {
    const abs = path.join(BEDS_DIR, name);
    if (!fs.existsSync(abs)) {
      console.warn("missing nature bed", name);
      continue;
    }
    sources.push({
      abs,
      masterUrl: urlFor(["beds", name]),
      runtimeParts: ["sample-runtime", "beds", name],
    });
  }
  sources.sort((a, b) => a.masterUrl.localeCompare(b.masterUrl));
  return sources;
}

function run(bin, args) {
  const result = spawnSync(bin, args, { encoding: "utf8" });
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || "").trim();
    throw new Error(`${bin} failed (${result.status}): ${detail}`);
  }
  return result.stdout || "";
}

function wavDuration(filePath) {
  const output = run("ffprobe", [
    "-v",
    "error",
    "-show_entries",
    "format=duration",
    "-of",
    "default=noprint_wrappers=1:nokey=1",
    filePath,
  ]);
  const duration = Number(output.trim());
  if (!Number.isFinite(duration) || duration <= 0) {
    throw new Error(`No duration for ${filePath}`);
  }
  return duration;
}

function outputPath(runtimeParts, ext) {
  const parts = runtimeParts.slice(1);
  const base = parts.pop().replace(/\.[^.]+$/, ext);
  return path.join(RUNTIME_DIR, ...parts, base);
}

function fresh(src, dest) {
  if (!fs.existsSync(dest)) return false;
  const sourceStat = fs.statSync(src);
  const destStat = fs.statSync(dest);
  return destStat.size > 1000 && destStat.mtimeMs >= sourceStat.mtimeMs;
}

function encode(src, dest, codecArgs) {
  if (fresh(src, dest)) {
    console.log("skip", path.relative(ROOT, dest));
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  console.log("encode", path.relative(ROOT, dest));
  run("ffmpeg", ["-y", "-i", src, "-ac", "1", "-ar", "48000", ...codecArgs, dest]);
}

function jsString(value) {
  return JSON.stringify(value);
}

function writeMap(beds) {
  const rows = beds
    .map((bed) => {
      const legacyUrl = bed.url.replace("/sample-runtime/", "/beds/runtime/");
      const legacyFallback = bed.fallbackUrl.replace("/sample-runtime/", "/beds/runtime/");
      const keys = [bed.masterUrl, bed.url, bed.fallbackUrl, legacyUrl, legacyFallback]
        .map(jsString)
        .join(", ");
      return `  {
    keys: [${keys}],
    url: ${jsString(bed.url)},
    fallbackUrl: ${jsString(bed.fallbackUrl)},
    loopDuration: ${bed.loopDuration.toFixed(6)},
    loopCrossfade: ${LOOP_CROSSFADE},
  }`;
    })
    .join(",\n");
  const source = `/**
 * Playback files for the selectable beds.
 * Generated by scripts/encode-runtime-beds.js. Do not edit by hand.
 */
export const RUNTIME_BEDS = [
${rows}
];

function decodeKey(url) {
  const pathOnly = String(url || "").split("?")[0].split("#")[0];
  try {
    return decodeURIComponent(pathOnly);
  } catch {
    return pathOnly;
  }
}

const BY_KEY = new Map();
for (const bed of RUNTIME_BEDS) {
  for (const key of bed.keys) BY_KEY.set(decodeKey(key), bed);
}

/** @param {string} url Master, WebM, or AAC url. */
export function resolveRuntimeBed(url) {
  if (!url) return null;
  return BY_KEY.get(decodeKey(url)) || null;
}
`;
  fs.writeFileSync(MAP_FILE, source);
  console.log("wrote", path.relative(ROOT, MAP_FILE));
}

function main() {
  const sources = collectSources();
  if (!sources.length) throw new Error("No source beds found");
  const beds = [];
  for (const source of sources) {
    const duration = wavDuration(source.abs);
    const webmParts = source.runtimeParts.slice();
    const webmName = webmParts[webmParts.length - 1].replace(/\.[^.]+$/, ".webm");
    const m4aName = webmParts[webmParts.length - 1].replace(/\.[^.]+$/, ".m4a");
    webmParts[webmParts.length - 1] = webmName;
    const m4aParts = source.runtimeParts.slice();
    m4aParts[m4aParts.length - 1] = m4aName;
    const webmFile = outputPath(source.runtimeParts, ".webm");
    const m4aFile = outputPath(source.runtimeParts, ".m4a");
    encode(source.abs, webmFile, ["-c:a", "libopus", "-b:a", "96k", "-vbr", "on"]);
    encode(source.abs, m4aFile, ["-c:a", "aac", "-b:a", "96k", "-movflags", "+faststart"]);
    const bed = {
      masterUrl: source.masterUrl,
      url: urlFor(webmParts),
      fallbackUrl: urlFor(m4aParts),
      loopDuration: duration,
    };
    beds.push(bed);
    console.log(
      `${source.masterUrl} ${duration.toFixed(3)}s webm ${fs.statSync(webmFile).size} m4a ${fs.statSync(m4aFile).size}`
    );
  }
  writeMap(beds);
}

main();
